"""results/bench.csv -> results/summary.md (tables) and results/*.png (charts).

Needs matplotlib. Run from the project folder: python bench/plot.py
"""
import csv
from collections import defaultdict
from statistics import median

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

POOL, SPAWN, SEQ = "#2a78d6", "#eb6834", "#1baf7a"
INK, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "font.size": 10,
    "axes.edgecolor": GRID, "axes.labelcolor": MUTED, "text.color": INK,
    "xtick.color": MUTED, "ytick.color": MUTED, "axes.grid": True,
    "grid.color": GRID, "axes.axisbelow": True, "axes.spines.top": False,
    "axes.spines.right": False, "legend.frameon": False,
    "axes.titlelocation": "left", "figure.dpi": 150, "lines.linewidth": 2,
    "lines.markersize": 7,
})

# (experiment, strategy, param, threads, tasks) -> seconds of every repetition
runs = defaultdict(list)
with open("results/bench.csv", newline="") as f:
    for r in csv.DictReader(f):
        runs[r["experiment"], r["strategy"], int(r["param"]), int(r["threads"]),
             int(r["tasks"])].append(float(r["seconds"]))


def rows(experiment):
    for (exp, strategy, param, threads, tasks), secs in runs.items():
        if exp == experiment:
            yield strategy, param, threads, tasks, secs


def save(fig, name):
    fig.tight_layout()
    fig.savefig(f"results/{name}.png")
    plt.close(fig)


# ---- tables ----------------------------------------------------------------
with open("results/summary.md", "w", encoding="utf-8") as f:
    f.write("# Summary of bench.csv\n\nGenerated by bench/plot.py. "
            "Times are milliseconds; median of 5 runs.\n")
    for exp in ("granularity", "pool_size", "io", "queue"):
        f.write(f"\n## {exp}\n\n| strategy | param | threads | tasks | median | "
                "min | max | us per task |\n|---|--:|--:|--:|--:|--:|--:|--:|\n")
        for strategy, param, threads, tasks, s in rows(exp):
            f.write(f"| {strategy} | {param} | {threads} | {tasks} | "
                    f"{median(s)*1e3:.2f} | {min(s)*1e3:.2f} | {max(s)*1e3:.2f} | "
                    f"{median(s)/tasks*1e6:.2f} |\n")

# ---- 1. granularity --------------------------------------------------------
fig, ax = plt.subplots(figsize=(8, 4.5))
for strategy, label, color, marker in (
        ("sequential", "sequential", SEQ, "s"),
        ("thread_per_task", "one thread per task", SPAWN, "^"),
        ("pool", "thread pool (12 workers)", POOL, "o")):
    pts = sorted((p, median(s) / n * 1e6, min(s) / n * 1e6, max(s) / n * 1e6)
                 for st, p, _, n, s in rows("granularity") if st == strategy)
    # An empty sequential task is a few ns: below the axis, so not drawn.
    pts = [(i, *p) for i, p in enumerate(pts) if p[1] >= 0.02]
    x, y = [p[0] for p in pts], [p[2] for p in pts]
    err = [[p[2] - p[3] for p in pts], [p[4] - p[2] for p in pts]]
    ax.errorbar(x, y, err, color=color, marker=marker, label=label, capsize=3)
params = sorted({p for _, p, *_ in rows("granularity")})
ax.set_yscale("log")
ax.set_xticks(range(len(params)), [f"{p} µs" for p in params])
ax.set_xlabel("CPU work in each task")
ax.set_ylabel("elapsed time per task (µs, log)")
ax.set_title("Cost per task by task size (lower is better)")
ax.legend()
save(fig, "granularity")

# ---- 2. pool size ----------------------------------------------------------
seq = next(median(s) for st, *_, s in rows("pool_size") if st == "sequential")
pts = sorted((th, seq / median(s)) for st, _, th, _, s in rows("pool_size")
             if st == "pool")
fig, ax = plt.subplots(figsize=(8, 4.5))
ax.plot([1, 12], [1, 12], color=MUTED, lw=1, ls="--")
ax.annotate("ideal", (9, 9), xytext=(-6, 6), textcoords="offset points",
            color=MUTED, ha="right")
ax.axvline(6, color=MUTED, lw=1, ls=":")
ax.annotate("6 physical cores", (6, 0.3), xytext=(5, 0),
            textcoords="offset points", color=MUTED)
ax.plot(*zip(*pts), color=POOL, marker="o")
ax.annotate(f"{pts[-1][1]:.1f}x", pts[-1], xytext=(0, 9),
            textcoords="offset points", ha="center")
ax.set_xticks([p[0] for p in pts])
ax.set_ylim(0)
ax.set_xlabel("worker threads")
ax.set_ylabel("speedup over sequential")
ax.set_title("Pool speedup, 100 µs CPU tasks (higher is better)")
save(fig, "pool_size")

# ---- 3. I/O ----------------------------------------------------------------
bars = sorted(((th, st, median(s) * 1e3) for st, _, th, _, s in rows("io")),
              key=lambda b: (b[1] == "thread_per_task", b[0]))
names = [f"pool, {th} workers" if st == "pool" else f"one thread per task ({th})"
         for th, st, _ in bars]
fig, ax = plt.subplots(figsize=(8, 3.2))
ax.barh(names, [b[2] for b in bars], height=0.55,
        color=[POOL if b[1] == "pool" else SPAWN for b in bars])
for i, b in enumerate(bars):
    ax.annotate(f"{b[2]:.0f} ms", (b[2], i), xytext=(5, 0),
                textcoords="offset points", va="center")
ax.invert_yaxis()
ax.grid(axis="y", visible=False)
ax.margins(x=0.12)
ax.set_xlabel("elapsed time (ms)")
ax.set_title("500 sleeping tasks, 10 ms requested each (lower is better)")
save(fig, "io")

# ---- 4. queue backends -----------------------------------------------------
pairs = sorted({th for _, _, th, *_ in rows("queue")})
caps = sorted({p for _, p, *_ in rows("queue")})
fig, axes = plt.subplots(1, len(pairs), figsize=(10, 4), sharey=True)
for ax, pair in zip(axes, pairs):
    for k, (backend, color) in enumerate((("condvar", POOL), ("semaphore", SPAWN))):
        y = [next(n / median(s) / 1e6 for st, p, th, n, s in rows("queue")
                  if (st, p, th) == (backend, c, pair)) for c in caps]
        x = [i + (k - 0.5) * 0.36 for i in range(len(caps))]
        ax.bar(x, y, width=0.32, color=color, label=backend)
        for xi, yi in zip(x, y):
            ax.annotate(f"{yi:.2f}" if yi < 1 else f"{yi:.1f}", (xi, yi),
                        xytext=(0, 3), textcoords="offset points", ha="center",
                        fontsize=8)
    ax.set_xticks(range(len(caps)), caps)
    ax.grid(axis="x", visible=False)
    ax.set_xlabel("queue capacity")
    ax.set_title(f"{pair} producer{'s' * (pair > 1)}, "
                 f"{pair} consumer{'s' * (pair > 1)}", fontsize=10)
axes[0].set_ylabel("million items per second")
axes[0].legend(loc="upper left")
fig.suptitle("Queue throughput by backend (higher is better)", x=0.01, ha="left")
save(fig, "queue")
